function getCurrentAndNextMonth(nowDate) {
  const d = nowDate || new Date();
  const curM = d.getMonth() + 1; // 1..12
  const nextM = curM === 12 ? 1 : curM + 1;
  return {
    current: MONTHLY_SURVIVAL_CALENDAR.find((x) => x.month === curM) || MONTHLY_SURVIVAL_CALENDAR[0],
    next: MONTHLY_SURVIVAL_CALENDAR.find((x) => x.month === nextM) || MONTHLY_SURVIVAL_CALENDAR[1]
  };
}

